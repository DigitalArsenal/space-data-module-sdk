// Build the self-contained browser worker bundles (design A39) into
// src/host/hostWorkerBundleSources.js.
//
// The dashboard ships as one HTML file whose CSP allows only `worker-src 'self'
// blob:`, so its workers cannot load the SDK's module worker files by URL. The
// SDK therefore ships each worker as one classic script (esbuild IIFE, no
// imports) that a host spawns from a blob: URL (src/host/hostWorkerBundles.js):
//
//   wasi-thread-pool  src/host/wasiThreadBrowserWorker.mjs (guest pthreads)
//   flatsql-io        src/host/opfsIoWorker.mjs            (FlatSQL I/O worker)
//
// Usage:  node scripts/build-host-worker-bundles.mjs [--check]
// --check exits 1 when the committed file differs from a fresh build.

import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const HOST_WORKER_BUNDLE_OUTPUT = path.join(repoRoot, "src/host/hostWorkerBundleSources.js");

export const HOST_WORKER_BUNDLE_ENTRIES = Object.freeze({
  "wasi-thread-pool": "src/host/wasiThreadBrowserWorker.mjs",
  "flatsql-io": "src/host/opfsIoWorker.mjs",
});

async function bundle(entry) {
  const esbuild = await import("esbuild");
  const result = await esbuild.build({
    entryPoints: [path.join(repoRoot, entry)],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: "es2022",
    minify: true,
    legalComments: "none",
    charset: "utf8",
    logLevel: "silent",
  });
  return result.outputFiles[0].text;
}

export async function renderHostWorkerBundleSources() {
  const lines = [
    "// GENERATED by scripts/build-host-worker-bundles.mjs. Do not edit.",
    "// Self-contained classic-script worker bundles, spawned from blob: URLs",
    "// (design A39). Rebuild after changing any file they bundle.",
    "",
  ];
  for (const [kind, entry] of Object.entries(HOST_WORKER_BUNDLE_ENTRIES)) {
    const text = await bundle(entry);
    const sha256 = createHash("sha256").update(text).digest("hex");
    const name = kind.replace(/-/g, "_").toUpperCase();
    lines.push(`/** ${entry}, sha256 ${sha256}. */`);
    lines.push(`export const ${name}_WORKER_BUNDLE = ${JSON.stringify(text)};`);
    lines.push(`export const ${name}_WORKER_BUNDLE_SHA256 = ${JSON.stringify(sha256)};`);
    lines.push("");
  }
  return lines.join("\n");
}

async function main() {
  const check = process.argv.includes("--check");
  const fresh = await renderHostWorkerBundleSources();
  if (check) {
    const committed = await readFile(HOST_WORKER_BUNDLE_OUTPUT, "utf8").catch(() => "");
    if (committed !== fresh) {
      console.error(
        "src/host/hostWorkerBundleSources.js is stale: run node scripts/build-host-worker-bundles.mjs",
      );
      process.exit(1);
    }
    console.log("host worker bundles are current");
    return;
  }
  await writeFile(HOST_WORKER_BUNDLE_OUTPUT, fresh);
  console.log(`wrote ${path.relative(repoRoot, HOST_WORKER_BUNDLE_OUTPUT)} (${fresh.length} bytes)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
